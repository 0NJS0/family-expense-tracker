"""Reading receipts: run Tesseract, then find a total and a date in the text.

Conservative on purpose. An amount is only suggested from a line that says it
is the total ("Total", "Grand total", "মোট", …); the largest number on a receipt
is as likely to be a phone or invoice number. Dates are read day-first, as
written in Bangladesh. Everything here is a suggestion that a person confirms.
"""

import re
import shutil
import subprocess
from datetime import date
from pathlib import Path

from app.money import MAX_TRANSACTION_POISHA, InvalidAmountError, parse_taka

_BANGLA_DIGITS = str.maketrans("০১২৩৪৫৬৭৮৯", "0123456789")
# "grand total" and "net payable" beat a plain "total"; "sub total" is never the total.
_TOTAL_WORDS = [
    (
        3,
        re.compile(
            r"grand\s*total|net\s*(total|payable)|total\s*payable|amount\s*due|সর্বমোট|সর্ব\s*মোট|মোট\s*প্রদেয়",
            re.I,
        ),
    ),
    (2, re.compile(r"(?<!sub)(?<!sub\s)\btotal\b|payable|মোট", re.I)),
]
_SUBTOTAL = re.compile(r"sub\s*-?\s*total|উপ\s*মোট", re.I)
_AMOUNT = re.compile(r"(?<![\d.,])(\d{1,3}(?:,\d{2,3})+|\d+)(?:\.(\d{1,2}))?(?![\d,]*\d)")
_DMY = re.compile(r"(?<!\d)(\d{1,2})[/.\-](\d{1,2})[/.\-](\d{4}|\d{2})(?!\d)")
_YMD = re.compile(r"(?<!\d)(\d{4})-(\d{2})-(\d{2})(?!\d)")
MAX_TEXT = 20_000


def _amounts(line: str) -> list[int]:
    found = []
    for match in _AMOUNT.finditer(line):
        text = match.group(1) + (f".{match.group(2)}" if match.group(2) else "")
        try:
            value = parse_taka(text)
        except InvalidAmountError:
            continue
        if 0 < value <= MAX_TRANSACTION_POISHA:
            found.append(value)
    return found


def find_total(text: str) -> int | None:
    """The amount on the strongest "total" line (the last one if several), else None."""
    best: tuple[int, int, int] | None = None  # (strength, line number, amount)
    for number, raw in enumerate(text.translate(_BANGLA_DIGITS).splitlines()):
        if _SUBTOTAL.search(raw):
            continue
        strength = next((s for s, pattern in _TOTAL_WORDS if pattern.search(raw)), 0)
        amounts = _amounts(raw)
        if strength and amounts:
            candidate = (strength, number, max(amounts))
            if best is None or candidate[:2] > best[:2]:
                best = candidate
    return best[2] if best else None


def find_date(text: str, today: date) -> date | None:
    """The first plausible date (day first), not in the future and not before 2000."""
    normalised = text.translate(_BANGLA_DIGITS)
    candidates: list[tuple[int, int, int]] = []
    for m in _YMD.finditer(normalised):
        candidates.append((int(m.group(1)), int(m.group(2)), int(m.group(3))))
    for m in _DMY.finditer(normalised):
        year = int(m.group(3))
        candidates.append((year + 2000 if year < 100 else year, int(m.group(2)), int(m.group(1))))
    for year, month, day in candidates:
        try:
            found = date(year, month, day)
        except ValueError:
            continue
        if date(2000, 1, 1) <= found <= today:
            return found
    return None


class OcrUnavailable(Exception):
    """Tesseract is not installed (the core app works without it)."""


def available_languages(binary: str = "tesseract") -> set[str]:
    path = shutil.which(binary)
    if path is None:
        raise OcrUnavailable("tesseract is not installed")
    out = subprocess.run(  # noqa: S603 - fixed binary, argument list, no shell
        [path, "--list-langs"], capture_output=True, text=True, timeout=30, check=False
    )
    return {line.strip() for line in out.stdout.splitlines()[1:] if line.strip()}


def read_image(path: Path, timeout_seconds: int = 120, binary: str = "tesseract") -> str:
    """Text of an image file. Bangla and English when both are installed."""
    langs = available_languages(binary)
    wanted = [lang for lang in ("ben", "eng") if lang in langs] or ["eng"]
    exe = shutil.which(binary)
    if exe is None:  # pragma: no cover - checked above
        raise OcrUnavailable("tesseract is not installed")
    # The path is ours (storage key generated by the server); no shell is used.
    out = subprocess.run(  # noqa: S603 - fixed binary, server-made path, no shell
        [exe, str(path), "stdout", "-l", "+".join(wanted), "--psm", "6"],
        capture_output=True,
        text=True,
        timeout=timeout_seconds,
        check=False,
    )
    if out.returncode != 0:
        raise RuntimeError("tesseract failed")
    return out.stdout[:MAX_TEXT]
