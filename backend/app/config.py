"""Application configuration loaded from environment variables.

All settings use the ``FET_`` prefix (Family Expense Tracker), e.g.
``FET_DATABASE_URL``. Production startup refuses insecure configuration.
"""

from enum import StrEnum
from functools import lru_cache
from typing import Annotated
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from pydantic import Field, SecretStr, field_validator, model_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict

INSECURE_DEV_SECRET = "dev-only-insecure-secret-change-me-0000000000"  # noqa: S105


class Environment(StrEnum):
    DEVELOPMENT = "development"
    TEST = "test"
    PRODUCTION = "production"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="FET_", env_file=".env", extra="ignore")

    environment: Environment = Environment.DEVELOPMENT
    database_url: str = Field(min_length=1)

    jwt_secret: SecretStr = SecretStr(INSECURE_DEV_SECRET)
    access_token_ttl_minutes: int = Field(default=15, ge=1, le=60)
    refresh_token_ttl_days: int = Field(default=60, ge=1, le=365)
    session_max_age_days: int = Field(default=365, ge=1, le=730)
    # A rotated refresh token presented again within this window is treated as a
    # lost-response retry rather than token theft (see docs/security.md).
    refresh_reuse_grace_seconds: int = Field(default=60, ge=0, le=300)

    cors_origins: Annotated[list[str], NoDecode] = Field(default_factory=list)
    default_timezone: str = "Asia/Dhaka"

    # Private storage for receipt files (a Docker volume in production). Never
    # served directly: files are only returned through the authorised API.
    receipts_dir: str = "var/receipts"
    max_receipt_bytes: int = Field(default=10 * 1024 * 1024, ge=1024, le=50 * 1024 * 1024)

    # Local AI (llama.cpp, OpenAI-compatible). AI is off when the URL is unset.
    llama_base_url: str | None = None
    llama_api_key: SecretStr | None = None
    llama_model: str = "local-model"
    # The homelab model is slow (about a second per prompt token): reports are
    # generated by the background worker, never inside a request.
    llama_timeout_seconds: int = Field(default=1800, ge=10, le=7200)
    worker_poll_seconds: int = Field(default=30, ge=1, le=3600)
    ocr_timeout_seconds: int = Field(default=120, ge=5, le=1800)

    login_rate_limit_per_minute: int = Field(default=10, ge=1)
    log_level: str = "INFO"

    @field_validator("cors_origins", mode="before")
    @classmethod
    def _split_origins(cls, value: object) -> object:
        if isinstance(value, str):
            return [origin.strip() for origin in value.split(",") if origin.strip()]
        return value

    @field_validator("default_timezone")
    @classmethod
    def _valid_timezone(cls, value: str) -> str:
        try:
            ZoneInfo(value)
        except (ZoneInfoNotFoundError, ValueError) as exc:
            raise ValueError(f"unknown timezone: {value}") from exc
        return value

    @model_validator(mode="after")
    def _production_safety(self) -> "Settings":
        if self.environment is Environment.PRODUCTION:
            secret = self.jwt_secret.get_secret_value()
            if secret == INSECURE_DEV_SECRET or len(secret) < 32:
                raise ValueError("FET_JWT_SECRET must be set to a random value of 32+ characters")
            if "*" in self.cors_origins:
                raise ValueError("FET_CORS_ORIGINS must not contain '*' in production")
            if any(origin.startswith("http://") for origin in self.cors_origins):
                raise ValueError("FET_CORS_ORIGINS must use https:// in production")
        return self

    @property
    def is_production(self) -> bool:
        return self.environment is Environment.PRODUCTION


@lru_cache
def get_settings() -> Settings:
    return Settings()  # values come from the environment
